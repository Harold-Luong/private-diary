async function register(page, suffix) {
  const email = `ui-${suffix}-${Date.now()}@example.com`
  await page.goto('/register')
  await page.getByLabel('Tên bạn', { exact: true }).fill('Minh Anh')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Mật khẩu', { exact: true }).fill('browser-test-long-password')
  await page.getByLabel('Xác nhận mật khẩu').fill('browser-test-long-password')
  await page.getByRole('button', { name: 'Tạo sổ nhật ký' }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
  await expect(page.getByRole('heading', { name: 'Chào Anh, hôm nay thế nào?' })).toBeVisible()
  return email
}

