test('mobile navigation, draft validation, responsive editor and recovery from network errors', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await register(page, 'mobile')
  await page.screenshot({ path: 'test-results/dashboard-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Mở menu' }).click()
  await page.getByRole('link', { name: 'Sổ nhật ký', exact: true }).click()
  await page.getByRole('main').getByRole('link', { name: 'Viết nhật ký', exact: true }).click()
  await page.getByRole('button', { name: 'Lưu hoàn chỉnh', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Hãy viết một chút nội dung')
  await page.getByLabel('Tiêu đề nhật ký').fill('Nháp trên điện thoại')
  await page.screenshot({ path: 'test-results/editor-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Lưu nháp', exact: true }).click()
  await expect(page.locator('.draft-badge')).toHaveText('Bản nháp')
  await page.route('**/api/v1/diaries?*', route => route.abort())
  await page.getByRole('link', { name: 'Trở về sổ nhật ký' }).click()
  await expect(page.getByRole('alert')).toContainText('Không thể kết nối máy chủ')
  await page.unroute('**/api/v1/diaries?*')
  await page.getByRole('button', { name: 'Thử lại', exact: true }).click()
  await expect(page.locator('.diary-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Mở menu' }).click()
  await page.getByRole('link', { name: 'Lịch nhật ký', exact: true }).click()
  await page.locator('.calendar-day.written').click()
  await expect(page.locator('.calendar-day-panel')).toContainText('1 trang viết đã lưu')
  await page.getByRole('link', { name: 'Mở trang viết' }).click()
  await expect(page.locator('.diary-card')).toHaveCount(1)
})
